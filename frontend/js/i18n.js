window.MM_t = function (key, vars) {
  var lang = (window.MM_STATE && window.MM_STATE.lang) || localStorage.getItem('mm_lang') || 'fa';
  var dict = window.MM_I18N[lang] || window.MM_I18N.fa;
  var s = dict[key] != null ? dict[key] : (window.MM_I18N.en[key] || key);
  if (vars) Object.keys(vars).forEach(function (k) {
    s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
  });
  return s;
};
